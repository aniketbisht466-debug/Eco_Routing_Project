"""
train_model.py
──────────────
Official training pipeline for the AI-Powered Eco-Routing Logistics Engine.

Steps:
  1. Load simulated_data.csv  (5,000 rows generated by generate_data.py)
  2. Train RandomForestRegressor on the four feature columns used by app.py
  3. Validate R² >= 98.73% on a held-out test split
  4. Save the fitted model as  fuel_model.pkl
  5. Export all EDA + validation plots as PNG assets

Feature columns (must match app.py exactly):
    Distance_km | Payload_Weight_kg | Traffic_Index | Hill_Slope_Percent
Target:
    Fuel_Consumed_Liters
"""

import numpy as np
import pandas as pd
import joblib
import matplotlib
matplotlib.use("Agg")          # headless – no display needed
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings("ignore")

from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error

sns.set_theme(style="whitegrid", palette="muted", font_scale=1.1)
plt.rcParams["figure.dpi"] = 120

# ─────────────────────────────────────────────────────────────────────────────
# 1. LOAD DATA
# ─────────────────────────────────────────────────────────────────────────────
print("Step 1: Loading simulated_data.csv ...")
df = pd.read_csv("simulated_data.csv")

assert df.shape[0] == 5000, f"Expected 5000 rows, got {df.shape[0]}"
assert df.isnull().sum().sum() == 0, "Null values detected in dataset!"

FEATURE_COLS = ["Distance_km", "Payload_Weight_kg", "Traffic_Index", "Hill_Slope_Percent"]
TARGET_COL   = "Fuel_Consumed_Liters"

for col in FEATURE_COLS + [TARGET_COL]:
    assert col in df.columns, f"Missing column: {col}"

print(f"   Shape : {df.shape}")
print(f"   Nulls : {df.isnull().sum().sum()}")
print(f"   Dupes : {df.duplicated().sum()}")
print(df.describe().round(3))

# ─────────────────────────────────────────────────────────────────────────────
# 2. EDA PLOTS
# ─────────────────────────────────────────────────────────────────────────────
print("\nStep 2: Generating EDA plots ...")

# 2a. Feature distributions
features = FEATURE_COLS + [TARGET_COL]
colors_p = ["#2196F3", "#4CAF50", "#FF9800", "#9C27B0", "#F44336"]
fig, axes = plt.subplots(2, 3, figsize=(16, 8))
axes = axes.flatten()
for i, (col, color) in enumerate(zip(features, colors_p)):
    axes[i].hist(df[col], bins=40, color=color, edgecolor="white", alpha=0.85)
    axes[i].set_title(col, fontweight="bold", fontsize=11)
    axes[i].set_xlabel("Value")
    axes[i].set_ylabel("Frequency")
axes[5].set_visible(False)
plt.suptitle("Feature Distributions — Synthetic Fleet Dataset", fontsize=14, fontweight="bold", y=1.01)
plt.tight_layout()
plt.savefig("eda_distributions.png", bbox_inches="tight")
plt.close()
print("   Saved: eda_distributions.png")

# 2b. Correlation heatmap
fig, ax = plt.subplots(figsize=(8, 6))
corr = df.corr()
mask = np.triu(np.ones_like(corr, dtype=bool))
sns.heatmap(corr, mask=mask, annot=True, fmt=".2f", cmap="RdYlGn",
            linewidths=0.5, ax=ax, vmin=-1, vmax=1, annot_kws={"size": 10})
ax.set_title("Feature Correlation Matrix", fontweight="bold", fontsize=13)
plt.tight_layout()
plt.savefig("eda_correlation.png", bbox_inches="tight")
plt.close()
print("   Saved: eda_correlation.png")

# 2c. Scatter plots vs fuel
fig, axes = plt.subplots(1, 4, figsize=(18, 4))
colors_s = ["#2196F3", "#4CAF50", "#FF9800", "#9C27B0"]
for ax, col, color in zip(axes, FEATURE_COLS, colors_s):
    ax.scatter(df[col], df[TARGET_COL], alpha=0.25, s=6, color=color, edgecolors="none")
    ax.set_xlabel(col, fontsize=10)
    ax.set_ylabel("Fuel (L)", fontsize=10)
    ax.set_title(f"{col} vs Fuel", fontweight="bold", fontsize=10)
plt.suptitle("Feature vs Fuel Consumed", fontsize=13, fontweight="bold")
plt.tight_layout()
plt.savefig("eda_scatter.png", bbox_inches="tight")
plt.close()
print("   Saved: eda_scatter.png")

# ─────────────────────────────────────────────────────────────────────────────
# 3. TRAIN / VALIDATE MODEL
# ─────────────────────────────────────────────────────────────────────────────
print("\nStep 3: Training RandomForestRegressor ...")
X = df[FEATURE_COLS]
y = df[TARGET_COL]

X_train, X_val, y_train, y_val = train_test_split(X, y, test_size=0.20, random_state=42)

model = RandomForestRegressor(
    n_estimators=300,
    max_depth=None,
    min_samples_split=2,
    min_samples_leaf=1,
    max_features="sqrt",
    n_jobs=-1,
    random_state=42,
)
model.fit(X_train, y_train)

y_pred = model.predict(X_val)
r2   = r2_score(y_val, y_pred)
mae  = mean_absolute_error(y_val, y_pred)
rmse = mean_squared_error(y_val, y_pred) ** 0.5

print("\n" + "=" * 47)
print("  VALIDATION PERFORMANCE METRICS")
print("=" * 47)
print(f"  R² Score  : {r2:.6f}   ({r2 * 100:.2f}%)")
print(f"  MAE       : {mae:.4f} L")
print(f"  RMSE      : {rmse:.4f} L")
print("=" * 47)

if r2 >= 0.9873:
    print(f"  SUCCESS: R² = {r2*100:.2f}% >= 98.73% target!")
else:
    raise RuntimeError(f"R² = {r2*100:.2f}% is below the 98.73% target. Check the dataset.")

# ─────────────────────────────────────────────────────────────────────────────
# 4. VALIDATION PLOTS
# ─────────────────────────────────────────────────────────────────────────────
print("\nStep 4: Generating model validation plots ...")
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Actual vs Predicted
axes[0].scatter(y_val, y_pred, alpha=0.35, s=8, color="#1565C0", edgecolors="none")
min_v, max_v = y_val.min(), y_val.max()
axes[0].plot([min_v, max_v], [min_v, max_v], "r--", lw=1.5, label="Perfect fit")
axes[0].set_xlabel("Actual Fuel (L)", fontsize=11)
axes[0].set_ylabel("Predicted Fuel (L)", fontsize=11)
axes[0].set_title(f"Actual vs Predicted  |  R² = {r2*100:.2f}%", fontweight="bold")
axes[0].legend()

# Residuals
residuals = y_val - y_pred
axes[1].hist(residuals, bins=50, color="#00897B", edgecolor="white", alpha=0.85)
axes[1].axvline(0, color="red", lw=1.5, linestyle="--")
axes[1].set_xlabel("Residual (Actual − Predicted)", fontsize=11)
axes[1].set_ylabel("Frequency", fontsize=11)
axes[1].set_title("Residuals Distribution", fontweight="bold")

plt.suptitle("Model Validation Diagnostics", fontsize=13, fontweight="bold")
plt.tight_layout()
plt.savefig("model_validation.png", bbox_inches="tight")
plt.close()
print("   Saved: model_validation.png")

# Feature importance
importances = pd.Series(model.feature_importances_, index=FEATURE_COLS).sort_values(ascending=True)
fig, ax = plt.subplots(figsize=(8, 4))
colors_imp = ["#EF5350", "#FF9800", "#42A5F5", "#66BB6A"]
importances.plot(kind="barh", ax=ax, color=colors_imp, edgecolor="white")
ax.set_title("Feature Importances — RandomForest", fontweight="bold", fontsize=12)
ax.set_xlabel("Importance Score")
for i, v in enumerate(importances):
    ax.text(v + 0.002, i, f"{v:.3f}", va="center", fontsize=9)
plt.tight_layout()
plt.savefig("feature_importance.png", bbox_inches="tight")
plt.close()
print("   Saved: feature_importance.png")

# ─────────────────────────────────────────────────────────────────────────────
# 5. RETRAIN ON FULL DATA & EXPORT MODEL
# ─────────────────────────────────────────────────────────────────────────────
print("\nStep 5: Retraining on full dataset and exporting fuel_model.pkl ...")
model.fit(X, y)
joblib.dump(model, "fuel_model.pkl")
print("   Saved: fuel_model.pkl")
print(f"   Feature order locked in: {FEATURE_COLS}")

print("\nAll files are synced and ready for submission.")
